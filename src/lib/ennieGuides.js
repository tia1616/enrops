// What Ennie's chat reads: the provider guides (src/content/guides), turned into
// one block of text for the model plus a table of the sections it may cite.
//
// The guides stay the ONE source. The server function cannot read src/, so
// scripts/build-ennie-guides.mjs writes this module's output into
// supabase/functions/ennie-help/guides.generated.ts, and guides.test.mjs fails
// when that file no longer matches the guides. Pure: no Vite, no fs.
import { parseGuide, sortGuides } from "./guideParse.js";

// files: [{ name: "1-get-your-link.md", text: "..." }] (README.md excluded by the caller)
export function buildEnnieGuides(files) {
  const guides = sortGuides(files.map((f) => parseGuide(f.text, f.name)));
  const sections = {};
  const blocks = [];
  for (const g of guides) {
    const label = g.stage != null ? `Step ${g.stage}` : "Questions";
    for (const s of g.sections) {
      if (s.id) sections[s.id] = { title: s.title, guide: g.title, label };
    }
    blocks.push(
      `<guide label="${label}" title="${g.title}">\n` +
        (g.goal ? `Goal: ${g.goal}\n\n` : "") +
        g.body.trim() +
        `\n</guide>`
    );
  }
  return { text: blocks.join("\n\n"), sections };
}

export function renderGeneratedModule({ text, sections }) {
  return (
    "// GENERATED by scripts/build-ennie-guides.mjs from src/content/guides. Do not edit.\n" +
    "// Edit the guide, then run: node scripts/build-ennie-guides.mjs\n" +
    `export const GUIDE_TEXT: string = ${JSON.stringify(text)};\n\n` +
    `export const SECTIONS: Record<string, { title: string; guide: string; label: string }> = ${JSON.stringify(sections, null, 2)};\n`
  );
}
